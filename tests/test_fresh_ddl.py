"""clockyn_ddl_fresh.sql (every CREATE and the default INSERTs for a NEW database) must stay the same schema as
clockyn_ddl_latest.sql. It is generated by scripts/build_fresh_ddl.py; these tests fail when someone edits the latest file and
forgets to regenerate it. DB-free (pglast parses both files).
Run: python -m pytest tests/test_fresh_ddl.py -q
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))

import build_fresh_ddl as B  # noqa: E402
import check_schema_consistency as C  # noqa: E402

LATEST = (ROOT / "clockyn_ddl_latest.sql").read_text(encoding="utf-8")
FRESH = (ROOT / "clockyn_ddl_fresh.sql").read_text(encoding="utf-8")


def code(sql: str) -> str:
    return "\n".join(line for line in sql.splitlines() if not line.lstrip().startswith("--"))


def inserts(sql: str):
    return [" ".join(m.group(0).split()) for m in re.finditer(r"(?ms)^INSERT INTO .*?;\s*$", code(sql))]


def test_the_fresh_file_is_up_to_date():
    assert B.build(LATEST) == FRESH.replace("\r\n", "\n"), "run: python scripts/build_fresh_ddl.py"


def test_same_schema_as_the_latest_file():
    a, b = C.load_catalog(LATEST), C.load_catalog(FRESH, "clockyn_ddl_fresh.sql")
    assert not a.errors and not b.errors, (a.errors, b.errors)
    assert sorted(a.tables) == sorted(b.tables) and len(a.tables) == 81
    for name, table in a.tables.items():
        assert repr(table) == repr(b.tables[name]), f"table {name} differs"
    assert {k: repr(v) for k, v in a.indexes.items()} == {k: repr(v) for k, v in b.indexes.items()}
    assert a.enums == b.enums and a.sequences == b.sequences and a.seeded == b.seeded


def test_same_default_rows_as_the_latest_file():
    fresh, latest = inserts(FRESH), inserts(LATEST)
    assert fresh and fresh == [i for i in latest if i in fresh]
    # the only INSERT of the latest file that the fresh file leaves out is the "existing database" copy of the plan rows
    assert [i for i in latest if i not in fresh] == [i for i in latest if "row_number() OVER" in i]
    tables = [re.match(r"INSERT INTO clockyn_dev\.(\w+)", i).group(1) for i in fresh]
    assert tables == ["role_info", "gen_plans", "settings", "app_version_control"]


def test_the_default_plans_are_three_durations_of_each_plan():
    seed = next(i for i in inserts(FRESH) if "clockyn_dev.gen_plans" in i)
    rows = re.findall(r"\((\d+), '(\w+)',\s*(\d+),\s*([\d.]+),\s*(\d+)\)", seed)
    assert {(n, int(m), int(f)) for _, n, m, _, f in rows} == {
        (n, m, f) for n in ("Core", "Prime", "Elite") for m, f in ((1, 0), (6, 1), (12, 2))}


def test_nothing_in_it_changes_an_existing_table():
    body = code(FRESH)
    for forbidden in (r"\bADD\s+COLUMN\b", r"\bDROP\s+(TABLE|COLUMN|CONSTRAINT|INDEX)\b", r"\bRENAME\s+TO\b", r"\bALTER\s+(INDEX|SEQUENCE|COLUMN)\b",
                      r"\b(UPDATE|DELETE\s+FROM|TRUNCATE)\b"):
        assert not re.search(forbidden, body, re.I), forbidden
    assert not re.search(r"(?im)^\s*ALTER\s+TABLE(?!.*\bADD\s+CONSTRAINT\b.*\bFOREIGN\s+KEY)", body)   # only the foreign keys
    assert "clockyn_ddl_latest.sql" in FRESH                                   # it says where it comes from
    assert not re.search(r"(?i)\b" + "punch" + "app", FRESH)                   # no legacy table or schema names


def test_every_object_is_qualified_with_the_one_schema():
    assert re.search(r"CREATE SCHEMA IF NOT EXISTS clockyn_dev;", FRESH)
    body = code(FRESH).replace(" IF NOT EXISTS", "")
    unqualified = re.findall(r"(?im)^CREATE (?:TABLE|SEQUENCE|TYPE) (?!clockyn_dev\.)\S+", body)
    assert unqualified == []
    assert len(re.findall(r"(?im)^CREATE (?:UNIQUE )?INDEX \S+ ON clockyn_dev\.", body)) == len(re.findall(r"(?im)^CREATE (?:UNIQUE )?INDEX ", body))
