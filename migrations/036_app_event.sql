-- 036: app_event (clickstream: screen views and button taps of the Clockyn app, read by the operator console's Clickstream page).
-- Apply with the target schema on the search_path, e.g. python migrate.py <schema> migrations/036_app_event.sql
-- (the same statements are in clockyn_ddl_latest.sql as clockyn_dev.app_event). Safe to re-run; deletes nothing.
--
-- One row per event the app sends to POST /analytics/events (batched, a few events per request):
--   event_type 'session' = the app was opened / came back after a long pause (name 'start'),
--   event_type 'screen'  = a screen was shown (name = the route pattern, e.g. /admin/staff/edit; never the real ids),
--   event_type 'click'   = a Button / IconButton was tapped (name = its label; screen = the screen it is on).
-- No personal content is stored: no typed text, no names, no phone numbers (the server also redacts anything that looks like
-- an e-mail or a long number). user_id / org_id are the same ids already used by support_video_view and live chat.
-- No foreign keys: the history must survive deleted staff / organisations, and inserts must stay cheap.
-- Retention: POST /gen-dashboard/clickstream/purge?days=N (operator, N >= 30) deletes older rows; nothing purges by itself.
-- No data pre-check is needed: the table is new.
CREATE TABLE IF NOT EXISTS app_event (
	id int8 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	event_time timestamptz DEFAULT now() NOT NULL,   -- when it happened on the device (clamped by the server), UTC
	received_at timestamptz DEFAULT now() NOT NULL,  -- when the server stored it
	session_id varchar(36) NOT NULL,                 -- random per app run (changes after 30 minutes in the background)
	user_id varchar(36) NOT NULL,                    -- users.user_id of the signed-in user
	org_id varchar(36) NOT NULL,                     -- the organisation (org_info.org_id) the user works in
	role_id int2 NULL,                               -- 1 admin, 2 manager, 3 staff
	platform varchar(10) NULL,                       -- android | ios | web
	app_version varchar(20) NULL,
	event_type varchar(10) NOT NULL,                 -- session | screen | click
	screen varchar(120) NULL,                        -- screen route pattern (for a click: the screen it was tapped on)
	target varchar(80) NULL,                         -- click label (null for screen / session events)
	CONSTRAINT app_event_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_app_event_time ON app_event USING btree (event_time DESC);
CREATE INDEX IF NOT EXISTS idx_app_event_org_time ON app_event USING btree (org_id, event_time DESC);
CREATE INDEX IF NOT EXISTS idx_app_event_user_time ON app_event USING btree (user_id, event_time DESC);
CREATE INDEX IF NOT EXISTS idx_app_event_session ON app_event USING btree (session_id, event_time);
