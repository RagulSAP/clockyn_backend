-- 037: Refer & Earn (referral codes, referrals and the 10 % rewards that come with them).
-- Apply with the target schema on the search_path, e.g. python migrate.py <schema> migrations/037_referral.sql
-- (the same statements are in clockyn_ddl_latest.sql as clockyn_dev.org_referral_code / referral / referral_reward and the two
-- new columns gen_orders.referral_reward_id / gen_invoices.referral_reward_id). Safe to re-run; deletes nothing.
--
-- Rules (core_functions/referral_functions.py is the only writer):
--   * every organisation has ONE permanent 6-character code (upper-case letters + digits, at least one of each, no 0 O 1 I L),
--     created lazily on first use; UNIQUE here is the final guard against two organisations getting the same code;
--   * a NEW organisation may enter a referrer's code while it registers: one `referral` row (referred_org_id is UNIQUE, so an
--     organisation can be referred once) and two `referral_reward` rows of 10 %:
--       role 'referred' -> status AVAILABLE at once, role 'referrer' -> status PENDING until the referred organisation's FIRST
--       paid plan is activated (referral.qualified_at is then set and the referrer's reward becomes AVAILABLE);
--   * a reward is usable once, on a new / renew purchase of Prime or Elite (status USED, used_* columns written in the same
--     transaction as the subscription and the invoice); status VOID = withdrawn by the operator console.
-- gen_orders.referral_reward_id = the reward the server priced into the order; gen_invoices.referral_reward_id = the reward this
-- invoice consumed. No foreign keys to org_info on purpose (the history must survive deleted organisations).
-- No data pre-check is needed: the tables are new and the two columns are nullable.
CREATE TABLE IF NOT EXISTS org_referral_code (
	org_id varchar(36) NOT NULL,
	code varchar(6) NOT NULL,
	created_at timestamptz DEFAULT now() NOT NULL,
	CONSTRAINT org_referral_code_pkey PRIMARY KEY (org_id),
	CONSTRAINT org_referral_code_code_key UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS referral (
	referral_id int4 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	referrer_org_id varchar(36) NOT NULL,
	referred_org_id varchar(36) NOT NULL,         -- UNIQUE: an organisation can be referred once
	code varchar(6) NOT NULL,                     -- the code that was entered at registration
	created_at timestamptz DEFAULT now() NOT NULL,
	qualified_at timestamptz NULL,                -- set when the referred organisation's first paid plan was activated
	CONSTRAINT referral_pkey PRIMARY KEY (referral_id),
	CONSTRAINT referral_referred_org_id_key UNIQUE (referred_org_id),
	CONSTRAINT referral_not_self_check CHECK (referrer_org_id <> referred_org_id)
);
CREATE INDEX IF NOT EXISTS idx_referral_referrer_org_id ON referral USING btree (referrer_org_id);

CREATE TABLE IF NOT EXISTS referral_reward (
	reward_id int4 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	referral_id int4 NOT NULL,
	org_id varchar(36) NOT NULL,                  -- the organisation that may use the reward
	role varchar(10) NOT NULL,                    -- 'referrer' | 'referred'
	status varchar(10) NOT NULL,                  -- 'PENDING' | 'AVAILABLE' | 'USED' | 'VOID'
	percent int4 DEFAULT 10 NOT NULL,
	created_at timestamptz DEFAULT now() NOT NULL,
	available_at timestamptz NULL,
	used_at timestamptz NULL,
	used_order_id int4 NULL,                      -- gen_orders.id of the purchase that used it
	used_invoice_number varchar(30) NULL,
	used_plan_name varchar(100) NULL,
	used_discount_amount numeric(10, 2) NULL,
	CONSTRAINT referral_reward_pkey PRIMARY KEY (reward_id),
	CONSTRAINT referral_reward_referral_fkey FOREIGN KEY (referral_id) REFERENCES referral(referral_id),
	CONSTRAINT referral_reward_role_check CHECK (role IN ('referrer', 'referred')),
	CONSTRAINT referral_reward_status_check CHECK (status IN ('PENDING', 'AVAILABLE', 'USED', 'VOID'))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_referral_reward_referral_role ON referral_reward USING btree (referral_id, role);
CREATE INDEX IF NOT EXISTS idx_referral_reward_org_status ON referral_reward USING btree (org_id, status);

ALTER TABLE gen_orders ADD COLUMN IF NOT EXISTS referral_reward_id int4 NULL;
ALTER TABLE gen_invoices ADD COLUMN IF NOT EXISTS referral_reward_id int4 NULL;
