-- 040: B2C referral (promoter codes) and the C2C discount percent kept in the database. Apply with the target schema on the
-- search_path, e.g.   python migrate.py <schema> migrations/040_b2c_referral.sql
-- Idempotent (safe to re-run); deletes nothing. The same objects are in clockyn_ddl_latest.sql.
--
-- B2C (business to customer): a promoter (a YouTube / Instagram / Facebook channel ...) gets a CUSTOM 6 character code
-- (b2c_partner). A new organisation that enters it while registering is stored in the same `referral` table as a C2C referral,
-- with partner_id set and referrer_org_id empty, and gets ONE reward (role 'referred') of the partner's discount_percent;
-- there is no referrer reward. The reward can expire (referral_reward.expires_at = signup + b2c_partner.reward_valid_days).
-- The promoter earns a commission once per organisation, when its first paid plan is activated (referral.commission_amount,
-- worked out then from b2c_partner.commission_type / commission_value); b2c_payout records what Clockyn has paid out.
--
-- C2C percent: referral_config is a one-row table (id = 1) with the discount of the customer-to-customer referral that used to
-- be fixed at 10 % in the code. A reward keeps the percent it was issued with, so a change affects NEW referrals only.
--
-- 1) new tables
CREATE TABLE IF NOT EXISTS b2c_partner (
	partner_id int4 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	code varchar(6) NOT NULL,                     -- typed by the operator: 6 characters A-Z / 0-9, unique here and never equal to a C2C code
	platform varchar(30) NOT NULL,                -- youtube | instagram | facebook | x | linkedin | whatsapp | telegram | blog | other
	channel_name varchar(150) NOT NULL,           -- shown to the new customer at signup
	channel_url varchar(300) NULL,
	contact_name varchar(150) NULL,
	phone varchar(20) NULL,
	email varchar(255) NULL,
	address text NULL,
	notes text NULL,
	discount_percent int4 NOT NULL,               -- % off Prime / Elite for a customer who used the code
	reward_valid_days int4 NULL,                  -- the customer's reward expires this many days after signup; NULL = never
	commission_type varchar(10) DEFAULT 'none' NOT NULL,   -- none | percent (of the first paid plan, excl. GST) | fixed (per paid customer)
	commission_value numeric(10, 2) DEFAULT 0 NOT NULL,
	status int2 DEFAULT 1 NOT NULL,               -- 1 = active (accepts new signups), 0 = inactive
	created_by varchar(255) NULL,
	created_at timestamptz DEFAULT now() NOT NULL,
	updated_at timestamptz DEFAULT now() NOT NULL,
	CONSTRAINT b2c_partner_pkey PRIMARY KEY (partner_id),
	CONSTRAINT b2c_partner_code_key UNIQUE (code),
	CONSTRAINT b2c_partner_code_check CHECK (code ~ '^[A-Z0-9]{6}$'),
	CONSTRAINT b2c_partner_discount_check CHECK (discount_percent BETWEEN 1 AND 100),
	CONSTRAINT b2c_partner_valid_days_check CHECK (reward_valid_days IS NULL OR reward_valid_days BETWEEN 1 AND 3650),
	CONSTRAINT b2c_partner_commission_type_check CHECK (commission_type IN ('none', 'percent', 'fixed')),
	CONSTRAINT b2c_partner_commission_value_check CHECK (commission_value >= 0),
	CONSTRAINT b2c_partner_status_check CHECK (status IN (0, 1))
);

CREATE TABLE IF NOT EXISTS b2c_payout (
	payout_id int4 GENERATED BY DEFAULT AS IDENTITY NOT NULL,
	partner_id int4 NOT NULL,
	amount numeric(10, 2) NOT NULL,
	paid_on date NOT NULL,
	reference varchar(100) NULL,                  -- bank / UPI reference
	note text NULL,
	created_by varchar(255) NULL,
	created_at timestamptz DEFAULT now() NOT NULL,
	CONSTRAINT b2c_payout_pkey PRIMARY KEY (payout_id),
	CONSTRAINT b2c_payout_partner_fkey FOREIGN KEY (partner_id) REFERENCES b2c_partner(partner_id),
	CONSTRAINT b2c_payout_amount_check CHECK (amount > 0)
);
CREATE INDEX IF NOT EXISTS idx_b2c_payout_partner_id ON b2c_payout USING btree (partner_id);

CREATE TABLE IF NOT EXISTS referral_config (
	id int2 DEFAULT 1 NOT NULL,
	c2c_percent int4 DEFAULT 10 NOT NULL,         -- discount of a customer-to-customer referral (both sides), for NEW referrals
	updated_at timestamptz DEFAULT now() NOT NULL,
	updated_by varchar(255) NULL,
	CONSTRAINT referral_config_pkey PRIMARY KEY (id),
	CONSTRAINT referral_config_single_row_check CHECK (id = 1),
	CONSTRAINT referral_config_percent_check CHECK (c2c_percent BETWEEN 1 AND 100)
);
