-- 2) referral: a B2C referral has no referrer organisation. ADD COLUMN without a default is metadata-only; DROP NOT NULL does not
--    rewrite the table. Existing rows keep their referrer, so the new check holds for them.
ALTER TABLE referral ADD COLUMN IF NOT EXISTS partner_id int4 NULL;                -- b2c_partner.partner_id (NULL for a C2C referral)
ALTER TABLE referral ADD COLUMN IF NOT EXISTS commission_amount numeric(10, 2) NULL;   -- promoter commission earned by this referral
ALTER TABLE referral ADD COLUMN IF NOT EXISTS qualified_order_id int4 NULL;        -- gen_orders.id of the first paid plan
ALTER TABLE referral ALTER COLUMN referrer_org_id DROP NOT NULL;
DO $$
BEGIN
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'referral_partner_fkey' AND conrelid = to_regclass('referral')) THEN
		ALTER TABLE referral ADD CONSTRAINT referral_partner_fkey FOREIGN KEY (partner_id) REFERENCES b2c_partner(partner_id);
	END IF;
	IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'referral_source_check' AND conrelid = to_regclass('referral')) THEN
		ALTER TABLE referral ADD CONSTRAINT referral_source_check CHECK (referrer_org_id IS NOT NULL OR partner_id IS NOT NULL);
	END IF;
END $$;
CREATE INDEX IF NOT EXISTS idx_referral_partner_id ON referral USING btree (partner_id);
