-- 5. Sequences
-- ----------------------------------------------------------------------------
-- drift object (gen_payment_functions.py:148): invoice numbers 'INV-<year>-<nnnn>'.
-- On an existing database continue from the highest issued number instead:
--   SELECT setval('punchapp_prod.gen_invoice_seq', <max number>);
CREATE SEQUENCE punchapp_prod.gen_invoice_seq START 1;
-- When gen_invoices already holds rows, continue after the highest numeric invoice number (a no-op on an empty
-- database; same block as migration 031).
DO $$
BEGIN
	IF EXISTS (SELECT 1 FROM punchapp_prod.gen_invoices) THEN
		PERFORM setval('punchapp_prod.gen_invoice_seq', GREATEST(
			COALESCE((SELECT max(substring(invoice_number FROM '([0-9]{1,15})$')::bigint) FROM punchapp_prod.gen_invoices), 0), 1));
	END IF;
END
$$;

