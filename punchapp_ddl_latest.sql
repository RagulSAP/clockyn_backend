
-- ============================================================================
-- Clockyn backend schema (legacy file name and schema qualifier kept for now)
-- ============================================================================
-- !! WARNING: this file qualifies EVERY object with the schema name used below (the legacy schema name). !!
-- !! Do NOT load it as it is into a database that already contains a schema with that name (for example a   !!
-- !! shared database holding the legacy data): it would create types / seed rows inside THAT schema.        !!
-- !! Use one of:                                                                                            !!
--      python migrate.py --all                      (rewrites the schema to DB_SCHEMA, records migrations)
--      python scripts/render_schema.py --schema <new_schema> --out file.sql   (a file safe to run by hand)
-- Only an EMPTY, dedicated database may take this file untouched (the steps below).
--
-- HOW TO RUN (empty database, run the whole file once, top to bottom)
--
--   1. Create a NEW, EMPTY PostgreSQL database (PostgreSQL 13 or newer; the code
--      uses gen_random_uuid(), which is built in from version 13):
--          createdb -h <host> -p <port> -U <user> <dbname>
--      or, from psql:   CREATE DATABASE <dbname>;
--
--   2. Load this file as-is. It creates the schema, the enum types, all tables,
--      indexes, foreign keys, the invoice sequence and a small idempotent seed
--      block, and stops at the first error:
--          psql -h <host> -p <port> -U <user> -d <dbname> -v ON_ERROR_STOP=1 -f punchapp_ddl_latest.sql
--      Python / psycopg2 equivalent (the file has no psql meta-commands, so a
--      single execute() works):
--          import psycopg2
--          conn = psycopg2.connect(host=..., port=..., user=..., password=..., dbname=...)
--          with conn, conn.cursor() as cur:
--              cur.execute(open("punchapp_ddl_latest.sql", encoding="utf-8").read())
--
--   3. Point the backend at it with these environment variables:
--          DB_HOST, DB_PORT, DB_USER, DB_PASSWORD, DB_NAME=<dbname>
--          DB_SCHEMA=punchapp_prod      (the schema created below; the app runs
--                                        "SET search_path TO <DB_SCHEMA>" on every
--                                        connection, which the unqualified enum
--                                        casts such as %s::incentive_type rely on)
--
-- Re-running: the tables are NOT idempotent (run on an empty database only).
-- The SEED section at the end of the file is idempotent and may be re-run.
-- Seed rows contain placeholders marked "OWNER:" that must be reviewed.
--
-- Layout: 1 schema, 2 enum types, 3 tables + indexes (alphabetical, drift
-- objects and Step-1 objects included in place), 4 foreign keys, 5 sequences,
-- 6 extra indexes, 7 seed data.
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. Schema
-- ----------------------------------------------------------------------------
CREATE SCHEMA IF NOT EXISTS punchapp_prod;

-- ----------------------------------------------------------------------------
-- 2. Enum types (referenced by columns below; they were missing from the dump)
-- Label sets: union of every literal the code writes/compares plus the labels
-- of the original design DDL (git history, punchapp_ddl_postgresql_New.sql).
-- Enum labels are case sensitive.
-- ----------------------------------------------------------------------------
-- gen_orders.status / gen_payments.status. Code writes CREATED (new order),
-- PAID (verify + webhook), FAILED (webhook), column default PENDING; the
