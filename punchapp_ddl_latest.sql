CREATE TABLE punchapp_prod.attendance (
	id int4 GENERATED ALWAYS AS IDENTITY( INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START 1 CACHE 1 NO CYCLE) NOT NULL,
	user_id varchar(36) NOT NULL,
	org_id varchar(36) NOT NULL,
	attendance_date date NOT NULL,
	punch_in timestamptz NULL,
	punch_out timestamptz NULL,
	work_hours numeric(5, 2) NULL,
	created_at timestamptz NULL,
	updated_at timestamptz NULL,
	punch_in_location point NULL,
	punch_out_location point NULL,
	punchinface text NULL,
	punchoutface text NULL,
	face_mismatch bool DEFAULT false NULL,
	-- forgotten punch-out closed by the server at the next punch-in (decision D-22); see migration 028
	auto_closed bool DEFAULT false NOT NULL,
	CONSTRAINT attendance_pkey PRIMARY KEY (id)
);
-- NEW-2 (migration 028): one row per SESSION, up to two sessions per user per day. The old unique index on
-- (user_id, attendance_date) (attendance_user_id_attendance_date_key) is gone: it forbade the second session the
-- punch code stores. There is no session-number column: a session is identified by its row id and ordered by
-- punch_in. The only uniqueness that matters is "at most one OPEN session per user" (partial unique index below);
-- the 2-sessions-per-day limit is enforced by the punch code under an advisory lock.
CREATE UNIQUE INDEX ux_attendance_one_open ON punchapp_prod.attendance USING btree (user_id) WHERE (punch_in IS NOT NULL AND punch_out IS NULL);
CREATE INDEX idx_attendance_date ON punchapp_prod.attendance USING btree (attendance_date);
CREATE INDEX idx_attendance_org_date ON punchapp_prod.attendance USING btree (org_id, attendance_date);
CREATE INDEX idx_attendance_org_id ON punchapp_prod.attendance USING btree (org_id);
CREATE INDEX idx_attendance_user_date ON punchapp_prod.attendance USING btree (user_id, attendance_date);
CREATE INDEX idx_attendance_user_id ON punchapp_prod.attendance USING btree (user_id);

